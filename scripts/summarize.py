"""Collect every result JSON into results/SUMMARY.md (numbers copied
verbatim from the run outputs; nothing is computed or rounded further)."""
import json
import sys
from pathlib import Path

R = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
RUNS = Path(sys.argv[2] if len(sys.argv) > 2 else "runs")
lines = ["# Results summary", "", "Generated by scripts/summarize.py from the JSON files in results/ and runs/.", ""]


def load(p):
    p = Path(p)
    return json.load(open(p)) if p.exists() else None


# --- speaker verification
v = load(R / "sv_vox1o.json")
if v:
    lines += ["## Speaker verification: VoxCeleb1-O (pipeline check)", "",
              f"- pretrained ECAPA-TDNN, cosine: EER {v['eer_percent']}% (model card {v['model_card_eer_percent']}%), "
              f"minDCF {v['min_dcf_p0.01']}, {v['n_trials']} trials", ""]
v2 = load(R / "sv_vox1o_finetuned.json")
if v2:
    lines += [f"- after SLURP fine-tuning: EER {v2['eer_percent']}%, minDCF {v2['min_dcf_p0.01']}", ""]
for tag in ("pretrained", "finetuned"):
    s = load(R / "sv" / f"sv_slurp_{tag}.json")
    if not s:
        continue
    lines += [f"## Speaker verification on SLURP, {tag} ({s['n_test_speakers']} held-out speakers, "
              f"{s['n_enroll_utts']}-utterance enrollment)", "",
              "| condition | scoring | trials | EER % | minDCF | FRR % @FAR 1% | FRR % @FAR 0.1% |", "|---|---|---|---|---|---|---|"]
    for cond, d in s["conditions"].items():
        for sc in ("cosine", "as_norm"):
            x = d[sc]
            lines.append(f"| {cond} | {sc} | {x['n_trials']} | {x['eer_percent']} | {x['min_dcf_p0.01']} | "
                         f"{x['frr_percent_at_far0.01']} | {x['frr_percent_at_far0.001']} |")
    lines.append("")
    n = load(R / "sv" / f"sv_slurp_noise_{tag}.json")
    if n:
        lines += [f"### Babble robustness ({tag}, headset enroll -> far-field test)", "",
                  "| SNR dB | EER % cosine | EER % AS-norm |", "|---|---|---|"]
        for k, d in n["snr_db"].items():
            lines.append(f"| {k} | {d['cosine']['eer_percent']} | {d['as_norm']['eer_percent']} |")
        lines.append("")
ws = {w: load(RUNS / "ecapa_ft" / f"train_stats_ws{w}.json") for w in (1, 2)}
if ws[1] and ws[2] and ws[1]["global_samples_per_sec"] and ws[2]["global_samples_per_sec"]:
    a, b = ws[1]["global_samples_per_sec"], ws[2]["global_samples_per_sec"]
    lines += ["## DDP scaling (ECAPA fine-tuning)", "",
              f"- 1 GPU: {a} samples/s, 2 GPUs: {b} samples/s -> speed-up {b / a:.2f}x, "
              f"scaling efficiency {100 * b / (2 * a):.1f}% ({ws[2]['gpu']})", ""]

# --- ASR / speech LLM
rows = []
for name in ("librispeech_test_clean", "slurp_test"):
    w = load(R / "asr" / f"wer_{name}.json")
    if w:
        rows.append(("Whisper-small", name, w))
s = load(R / "sllm" / "sllm_eval.json")
s_g = load(R / "sllm_grpo" / "sllm_eval.json")
if rows or s:
    lines += ["## ASR WER (Whisper EnglishTextNormalizer on refs and hyps)", "", "| system | set | WER % |", "|---|---|---|"]
    for sysname, name, w in rows:
        lines.append(f"| {sysname} | {name} (all) | {round(100 * w['all']['wer'], 2)} |")
        for c in ("headset", "farfield"):
            if c in w:
                lines.append(f"| {sysname} | {name} {c} | {round(100 * w[c]['wer'], 2)} |")
    for name, res in (("speech LLM (SFT)", s), ("speech LLM (SFT+GRPO)", s_g)):
        if res:
            for k, d in res["sets"].items():
                if "wer" in d:
                    lines.append(f"| {name} | {k} | {round(100 * d['wer'], 2)} |")
    lines.append("")
if s or s_g:
    lines += ["## End-to-end SLU from audio (speech LLM, official SLURP metric)", "",
              "| system | condition | intent F1 | SLU-F1 | JSON parse rate |", "|---|---|---|---|---|"]
    for name, res in (("SFT", s), ("SFT+GRPO", s_g)):
        if not res:
            continue
        for k, d in res["sets"].items():
            if "official" in d:
                o = d["official"]
                lines.append(f"| {name} | {k} | {o.get('intent (scen_act)', {}).get('f1')} | "
                             f"{o.get('slu f1', {}).get('f1')} | {d['json_parse_rate']} |")
    lines.append("")
gs = load(RUNS / "sllm_grpo" / "grpo_stats.json")
if gs:
    dev = [x for x in gs["log"] if "dev_reward" in x]
    lines += [f"- speech-LLM GRPO dev reward: step {dev[0]['step']} {dev[0]['dev_reward']} -> step "
              f"{dev[-1]['step']} {dev[-1]['dev_reward']} ({gs['steps']} steps)", ""]

# --- SLU SFT vs GRPO
e = load(R / "slu" / "slu_eval.json")
if e:
    lines += ["## Cascade SLU on Whisper transcripts: SFT vs SFT+GRPO (official SLURP metric)", "",
              "| system | input | n | intent F1 | SLU-F1 | mean reward | parse rate |", "|---|---|---|---|---|---|---|"]
    for k, d in e.items():
        sysname, inp = k.split("|")
        o = d["official"]
        lines.append(f"| {sysname} | {inp} | {d['n']} | {o.get('intent (scen_act)', {}).get('f1')} | "
                     f"{o.get('slu f1', {}).get('f1')} | {d['mean_reward']} | {d['json_parse_rate']} |")
    lines.append("")
g = load(RUNS / "slu" / "grpo_stats.json")
if g:
    dev = [x for x in g["log"] if "dev_reward" in x]
    if dev:
        lines += [f"- GRPO dev reward: step {dev[0]['step']} {dev[0]['dev_reward']} -> step {dev[-1]['step']} "
                  f"{dev[-1]['dev_reward']} ({g['steps']} steps, {g['prompts_per_step']} prompts x {g['group']} samples)", ""]

# --- directed-speech detection
dd = load(R / "ddsd" / "ddsd_eval.json")
if dd:
    lines += ["## Device-directed speech detection (leave-corpus-out)", "",
              f"Utterances after the shared filter: {dd['filtered_counts']}", "",
              "| fold | model | in-domain AUC | cross-corpus AUC | cross-corpus EER % |", "|---|---|---|---|---|"]
    for fname, f in dd["folds"].items():
        for m, v in f["models"].items():
            lines.append(f"| {fname} | {m} | {v['in_domain']['auc']} | {v['cross_corpus']['auc']} | "
                         f"{v['cross_corpus']['eer_percent']} |")
    lines.append("")

# --- LLM-size scaling
scale_rows = []
for tag in ("0.5B", "1.5B", "3B"):
    st, ev = load(RUNS / f"sllm_scale_{tag}" / "train_stats.json"), load(R / f"sllm_scale_{tag}" / "sllm_eval.json")
    if st and ev:
        sets = ev["sets"]
        slu = sets.get("slurp_test_farfield_slu", {}).get("official", {})
        scale_rows.append(f"| {tag} | {st['trainable_params_m']} | {st['samples_per_sec']} | {st['peak_gpu_mem_gb']} | "
                          f"{st['train_minutes']} | {round(100 * sets['librispeech_test_clean']['wer'], 2) if 'librispeech_test_clean' in sets else ''} | "
                          f"{round(100 * sets['slurp_test_farfield_asr']['wer'], 2)} | {slu.get('slu f1', {}).get('f1')} |")
if scale_rows:
    lines += ["## Speech-LLM size scaling (same data, steps, global batch; eval capped at 2000 per set)", "",
              "| LLM | trainable M | samples/s | peak GPU GB | train min | LS test-clean WER % | SLURP far-field WER % | far-field SLU-F1 |",
              "|---|---|---|---|---|---|---|---|", *scale_rows, ""]

Path(R / "SUMMARY.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
