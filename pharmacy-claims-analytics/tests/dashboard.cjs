// Optional UI logic test: npm install && npm test (does not test visual layout).
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM, VirtualConsole } = require('jsdom');
const errors = [];
const vc = new VirtualConsole();
vc.on('jsdomError', e => errors.push(e.message));
const dom = new JSDOM(fs.readFileSync(path.join(__dirname, '../reports/dashboard.html'), 'utf8'), {runScripts:'dangerously', virtualConsole:vc});
const doc = dom.window.document;
const before = doc.getElementById('ranking').textContent;
const select = doc.getElementById('capacity');
select.selectedIndex = 1;
select.dispatchEvent(new dom.window.Event('change'));
if (before === doc.getElementById('ranking').textContent) throw Error('Capacity interaction failed');
const workflow = doc.getElementById('workflow').textContent;
const reason = doc.getElementById('reason');
reason.selectedIndex = 1;
reason.dispatchEvent(new dom.window.Event('change'));
if (workflow === doc.getElementById('workflow').textContent) throw Error('Reason interaction failed');
if (doc.querySelectorAll('#cards .card').length !== 4) throw Error('KPI cards missing');
if (doc.querySelectorAll('#models tr').length !== 3) throw Error('Model table incomplete');
if (errors.length) throw Error(errors.join(';'));
console.log('PASS: dashboard executes without JS errors; capacity/reason filters, KPI cards, model table. Visual rendering not tested.');
dom.window.close();
